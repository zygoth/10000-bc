#!/usr/bin/env node
/**
 * Scans public/sounds/music/ and writes public/sounds/music/manifest.json.
 * Run: node ./scripts/build-music-manifest.mjs
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.join(__dirname, '..');
const musicRoot = path.join(repoRoot, 'public', 'sounds', 'music');

const EXT = new Set(['.ogg', '.mp3', '.wav', '.m4a']);

const SEASONS = ['spring', 'summer', 'fall', 'winter'];

function listAudioUrls(absDir, webBase) {
  if (!fs.existsSync(absDir)) {
    return [];
  }
  return fs
    .readdirSync(absDir)
    .filter((f) => EXT.has(path.extname(f).toLowerCase()))
    .sort()
    .map((f) => `${webBase}/${f}`);
}

function main() {
  const gameplay = {};
  for (const season of SEASONS) {
    const dir = path.join(musicRoot, 'gameplay', season);
    const base = `/sounds/music/gameplay/${season}`;
    gameplay[season] = listAudioUrls(dir, base);
  }

  const debriefDir = path.join(musicRoot, 'debrief');
  const debrief = listAudioUrls(debriefDir, '/sounds/music/debrief');

  if (!fs.existsSync(musicRoot)) {
    fs.mkdirSync(musicRoot, { recursive: true });
  }

  const out = {
    version: 1,
    generatedAt: new Date().toISOString(),
    comment: 'Generated by npm run music:build. Add audio under gameplay/<season>/ or debrief/ then re-run.',
    gameplay,
    debrief,
  };

  const outPath = path.join(musicRoot, 'manifest.json');
  fs.writeFileSync(outPath, JSON.stringify(out, null, 2), 'utf8');
  // eslint-disable-next-line no-console
  console.log(`Wrote ${outPath}`);
  for (const s of SEASONS) {
    // eslint-disable-next-line no-console
    console.log(`  gameplay/${s}: ${gameplay[s].length} file(s)`);
  }
  // eslint-disable-next-line no-console
  console.log(`  debrief: ${debrief.length} file(s)`);
}

main();
