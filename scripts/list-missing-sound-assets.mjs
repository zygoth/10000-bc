#!/usr/bin/env node
/**
 * Lists ambient catalog sound URLs vs files under public/.
 * Writes public/sounds/ambient/variant-manifest.json for _v1, _v2, … variant files.
 * Run from repo root: npm run sounds:missing
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { buildAmbientVariantGroupMap } from '../src/ambientAudio/ambientSoundVariants.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.join(__dirname, '..');
const catalogDir = path.join(repoRoot, 'src', 'ambientAudio', 'catalog');
const publicRoot = path.join(repoRoot, 'public');
const ambientSoundDir = path.join(publicRoot, 'sounds', 'ambient');

function collectUrlsFromValue(value, out) {
  if (value == null) {
    return;
  }
  if (typeof value === 'string' && value.startsWith('/sounds/')) {
    out.push(value);
    return;
  }
  if (Array.isArray(value)) {
    for (const v of value) {
      collectUrlsFromValue(v, out);
    }
    return;
  }
  if (typeof value === 'object') {
    for (const v of Object.values(value)) {
      collectUrlsFromValue(v, out);
    }
  }
}

function main() {
  if (!fs.existsSync(catalogDir)) {
    // eslint-disable-next-line no-console
    console.error('Catalog dir not found:', catalogDir);
    process.exit(1);
  }
  const files = fs.readdirSync(catalogDir).filter((f) => f.endsWith('.json'));
  const rows = [];
  for (const file of files) {
    const full = path.join(catalogDir, file);
    const json = JSON.parse(fs.readFileSync(full, 'utf8'));
    const urls = [];
    collectUrlsFromValue(json, urls);
    const speciesId = typeof json.species_id === 'string' ? json.species_id : file;
    for (const url of urls) {
      const rel = url.replace(/^\//, '');
      const diskPath = path.join(publicRoot, rel);
      const exists = fs.existsSync(diskPath);
      let generationPrompt = '';
      if (Array.isArray(json.calls)) {
        const call = json.calls.find((c) => c.url === url);
        if (call && typeof call.generation_prompt === 'string') {
          generationPrompt = call.generation_prompt;
        }
      }
      rows.push({
        catalog_file: file,
        species_id: speciesId,
        url,
        public_path: diskPath,
        exists,
        generation_prompt: generationPrompt,
      });
    }
  }

  const missing = rows.filter((r) => !r.exists);
  const outPath = path.join(repoRoot, 'missing-sounds-report.json');
  fs.writeFileSync(outPath, JSON.stringify({ generatedAt: new Date().toISOString(), missing, all: rows }, null, 2));
  // eslint-disable-next-line no-console
  console.log(`Wrote ${outPath} (${missing.length} missing of ${rows.length} URLs)`);
  if (missing.length) {
    for (const m of missing) {
      // eslint-disable-next-line no-console
      console.log('  MISSING', m.url);
    }
  }

  const allUrls = [...new Set(rows.map((r) => r.url))];
  const diskNames = fs.existsSync(ambientSoundDir)
    ? fs.readdirSync(ambientSoundDir).filter((f) => /\.(ogg|wav|mp3|m4a)$/i.test(f))
    : [];
  const groups = buildAmbientVariantGroupMap(allUrls, diskNames);
  const manifestPath = path.join(ambientSoundDir, 'variant-manifest.json');
  const manifest = {
    version: 1,
    comment: 'Generated by npm run sounds:missing. Add name.ogg + name_v1.ogg etc.; runtime picks at random per play.',
    groups,
  };
  if (!fs.existsSync(ambientSoundDir)) {
    fs.mkdirSync(ambientSoundDir, { recursive: true });
  }
  fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2));
  const nFiles = Object.values(groups).reduce((a, g) => a + g.length, 0);
  // eslint-disable-next-line no-console
  console.log(`Wrote ${manifestPath} (${Object.keys(groups).length} logical URLs, ${nFiles} files on disk in groups)`);
}

main();
